/**
 * Keeps search engines off every Netlify build that isn't the live domain (ticket 701).
 *
 * Netlify sets URL to the site's primary URL and CONTEXT to the deploy type. Until the custom domain moves to this
 * site (ticket 1204), URL is the *.netlify.app address, so the build writes dist/_headers with an X-Robots-Tag
 * noindex for every path. Deploy previews and branch deploys get it always. Netlify merges _headers with the
 * headers in netlify.toml.
 *
 * It's a header, not robots.txt: a robots.txt Disallow stops crawlers from ever seeing a noindex, and can still
 * leave blocked URLs in results. Local and CI builds (no NETLIFY env var) are left alone.
 *
 * The check runs at build time, so after the domain swap the site needs a fresh deploy to drop the header.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export default function noindexUntilLive({ liveUrl }) {
  return {
    name: 'noindex-until-live',
    hooks: {
      'astro:build:done': ({ dir, logger }) => {
        if (process.env.NETLIFY !== 'true') return;

        const { CONTEXT, URL } = process.env;
        const live = CONTEXT === 'production' && URL?.replace(/\/$/, '') === liveUrl;
        if (live) {
          logger.info(`Indexable: production build on ${URL}`);
          return;
        }

        const headers = [
          '# Generated by integrations/noindex-until-live.mjs (ticket 701). Not the live domain, so no indexing.',
          '/*',
          '  X-Robots-Tag: noindex, nofollow',
          '',
        ].join('\n');
        writeFileSync(join(fileURLToPath(dir), '_headers'), headers);
        logger.warn(`noindex on every path: context ${CONTEXT}, URL ${URL}, live is ${liveUrl}`);
      },
    },
  };
}
