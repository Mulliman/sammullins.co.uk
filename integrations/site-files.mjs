/**
 * Build-time site files (tickets 403, 601):
 *  - copies every legacy media master to a stable public path: /media/<id>/<name>.avif
 *  - writes dist/_redirects (page redirects + every legacy media original/crop → stable copy)
 *  - validates redirects (no loops, no chains, targets exist)
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export default function siteFiles() {
  return {
    name: 'site-files',
    hooks: {
      'astro:build:done': ({ dir, logger }) => {
        const out = fileURLToPath(dir);
        const root = process.cwd();
        const lines = ['# Generated by integrations/site-files.mjs. Do not edit; change src/data/redirects.json.'];

        // Page redirects
        const pageRedirects = JSON.parse(readFileSync(join(root, 'src/data/redirects.json'), 'utf8'));
        const map = new Map(Object.entries(pageRedirects).map(([from, r]) => [from, r]));
        for (const [from, r] of map) {
          if (map.has(r.to))
            throw new Error(`Redirect chain: ${from} → ${r.to} → ${map.get(r.to).to}. Point ${from} at the final URL.`);
          if (from === r.to) throw new Error(`Redirect loop: ${from}`);
          if (r.to.startsWith('/') && !existsSync(join(out, r.to, 'index.html')) && !existsSync(join(out, r.to))) {
            throw new Error(`Redirect target does not exist in the build: ${from} → ${r.to}`);
          }
          lines.push(`${from} ${r.to} ${r.status ?? 301}`);
          // Also catch the no-trailing-slash form.
          if (from.endsWith('/')) lines.push(`${from.slice(0, -1)} ${r.to} ${r.status ?? 301}`);
        }

        // Legacy media
        const mapFile = join(root, '_docs/legacy/media-map.json');
        let copied = 0;
        if (existsSync(mapFile)) {
          const media = JSON.parse(readFileSync(mapFile, 'utf8'));
          lines.push('', '# Legacy /media paths → stable optimised copies (ticket 403)');
          for (const m of media) {
            const asset = m.asset;
            const publicPath = '/' + asset.replace(/^src\/assets\//, '');
            const src = join(root, asset);
            if (!existsSync(src)) {
              logger.warn(`media master missing: ${asset}`);
              continue;
            }
            const dest = join(out, publicPath);
            mkdirSync(dirname(dest), { recursive: true });
            copyFileSync(src, dest);
            copied++;
            for (const legacy of [m.legacyPath, ...(m.legacyCrops ?? [])]) {
              if (legacy && legacy !== publicPath) lines.push(`${legacy} ${publicPath} 301`);
            }
          }
        } else {
          logger.warn('_docs/legacy/media-map.json not found; legacy media redirects skipped');
        }

        writeFileSync(join(out, '_redirects'), lines.join('\n') + '\n');
        logger.info(`_redirects written (${lines.length} lines), ${copied} legacy media copies`);
      },
    },
  };
}
