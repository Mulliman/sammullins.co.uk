#!/usr/bin/env node
// Copies .agents/skills/** (canonical) to .claude/skills/** (Claude Code reads only this path).
// The copy is GENERATED and committed, so a fresh clone works without running anything.
// Edit the files under .agents/skills/, never the copy. See _docs/agent-tooling.md.
//
// Usage:
//   node scripts/skills/sync.mjs           # write the copy (and remove stale generated skills)
//   node scripts/skills/sync.mjs --check   # exit 1 if the copy differs from the source (CI)

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(REPO, '.agents', 'skills');
const DEST = join(REPO, '.claude', 'skills');
const MARK = 'GENERATED by scripts/skills/sync.mjs';

const checkOnly = process.argv.includes('--check');

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

/** Adds a generated-file header. Front matter stays first, so the header goes inside it as a YAML comment. */
function withHeader(text, srcRel) {
  const header = `${MARK} from .agents/skills/${srcRel}. Do not edit; edit the source.`;
  if (text.startsWith('---\n')) {
    return text.replace(/^---\n/, `---\n# ${header}\n`);
  }
  return `<!-- ${header} -->\n${text}`;
}

const expected = new Map(); // dest path -> content (string or Buffer)
for (const file of walk(SRC)) {
  const rel = relative(SRC, file).split(sep).join('/');
  const dest = join(DEST, rel);
  if (/\.(md|mdx)$/i.test(file)) {
    expected.set(dest, withHeader(readFileSync(file, 'utf8'), rel));
  } else {
    expected.set(dest, readFileSync(file));
  }
}

// Stale generated copies: anything under .claude/skills that carries the marker but has no source.
const stale = walk(DEST).filter((f) => {
  if (expected.has(f)) return false;
  return readFileSync(f, 'utf8').includes(MARK);
});

let problems = [];
for (const [dest, content] of expected) {
  const existing = existsSync(dest) ? readFileSync(dest) : null;
  const same = existing !== null && Buffer.compare(existing, Buffer.from(content)) === 0;
  if (!same) problems.push(`out of date: ${relative(REPO, dest)}`);
}
for (const f of stale) problems.push(`stale generated file: ${relative(REPO, f)}`);
for (const f of walk(DEST)) {
  if (!expected.has(f) && !stale.includes(f)) problems.push(`not from source (hand-written?): ${relative(REPO, f)}`);
}

if (checkOnly) {
  if (problems.length) {
    console.error(problems.join('\n'));
    console.error('run: pnpm skills:sync, then commit the result');
    process.exit(1);
  }
  console.log(`.claude/skills is in sync with .agents/skills (${expected.size} files)`);
  process.exit(0);
}

for (const f of stale) rmSync(f);
for (const [dest, content] of expected) {
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, content);
}
console.log(`synced ${expected.size} files to .claude/skills (${stale.length} stale removed)`);
